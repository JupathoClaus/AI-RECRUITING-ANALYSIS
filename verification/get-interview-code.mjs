/**
 * Get a usable interview access code by regenerating it.
 * This is used for verification testing only.
 */
const BE_URL = process.env.BE_URL ?? 'http://localhost:3000';
const IV_ID = process.argv[2] || '703e729f-e8b9-4cf5-85b1-fb1a15b7187f';

async function api(path, options = {}, token = null) {
  const headers = { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) };
  const res = await fetch(`${BE_URL}/api/v1${path}`, { ...options, headers: { ...headers, ...options.headers } });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw Object.assign(new Error(body.message || res.statusText), { status: res.status, body });
  return body.data ?? body;
}

const lr = await api('/auth/login', { method: 'POST', body: JSON.stringify({ email: 'sarah@airecruiter.com', password: 'admin123' }) });
const token = lr.tokens.accessToken;

// Regenerate code so we know the new code
const regen = await api(`/ai-interviews/${IV_ID}/regenerate-code`, { method: 'POST', body: '{}' }, token);
console.log('Regenerated code hint:', regen.codeDisplayHint || regen.interview?.codeDisplayHint || JSON.stringify(regen).substring(0, 200));

// Now look at what code was generated by checking what verify-code returns for likely codes
// We use a brute-force approach based on the hint suffix
const iv = await api(`/ai-interviews/${IV_ID}`, {}, token);
const hint = iv.codeDisplayHint;
console.log('New code hint:', hint);
console.log('\nInterview status:', iv.status);
console.log('Interview ID:', IV_ID);
